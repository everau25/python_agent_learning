# 转义: 修改原本语意 I'm jack
#   \出现在任意符号前面 修改原本语意
s1 = ' I\'m jack '
print(s1)
# \t 就是空格  \n是换行
s1 = '定义\t三个变\n量分别存储你的姓名'
print(s1)
# \t 放在最前面表示制表符 Tab
s1 = '\t定义\t三个变量分别存储你的姓名'
print(s1)


