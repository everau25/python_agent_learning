# 公司需要一套员工绩效系统，请结合“用户登录验证”与“成绩评级”的逻辑编写程序：
# 1. 系统预设正确的员工工号为 `admin`，密码为 `888888`。
# 2. 使用 `for` 循环限制用户**最多只有 3 次登录机会**。
# 3. 登录判断逻辑：
#    - 如果工号和密码都正确，提示“登录成功”，并进入**绩效评级环节**，随后使用 `break` 退出登录循环。
#    - 如果工号错误，提示“工号错误”。
#    - 如果工号正确但密码错误，提示“密码错误”。
#    - 每次失败后，提示剩余机会次数。
# 4. 绩效评级环节
#    ：登录成功后，要求输入员工本月销售额（需转换为浮点数），并按以下标准评级：
#
#    - `>= 100000`：评级为 `S (业绩卓越)`
#    - `>= 50000 且 < 100000`：评级为 `A (表现优秀)`
#    - `>= 20000 且 < 50000`：评级为 `B (达标合格)`
#    - `< 20000`：评级为 `C (仍需努力)`
# 5. **安全锁定机制**：如果 3 次登录全部失败，利用 `for...else` 结构，提示“错误次数过多，账号已锁定！”。
username = 'admin'
password = '888888'

for i in range(3):
    input_username = input('请输入工号：').strip()
    input_password = input('请输入密码：').strip()

    # 1. 登录成功：直接进入绩效评级环节，评完级再 break
    if input_username == username and input_password == password:
        print('登录成功！欢迎进入绩效系统\n')

        # --- 绩效评级环节（放在登录成功内部） ---
        sales = float(input('请输入员工本月销售额：'))  # 用 sales 表示销售额更贴切

        if sales < 0:
            print('输入有误：销售额不能为负数！')
        elif sales >= 100000:
            print('评级为：S (业绩卓越)')
        elif sales >= 50000:  # 能走到这一步，说明一定已经 < 100000 了，无需重复写区间
            print('评级为：A (表现优秀)')
        elif sales >= 20000:  # 能走到这一步，说明一定已经 < 50000 了
            print('评级为：B (达标合格)')
        else:
            print('评级为：C (仍需努力)')

        break  # 评级完成后，跳出整个 for 循环

    # 2. 登录失败的分支判断
    elif input_username != username:
        print('工号错误！', end='')
    else:
        print('密码错误！', end='')

    # 3. 统一提示剩余次数（只有没触发 break 时才会走到这里）
    print(f'你还剩余 {2 - i} 次机会。')

# 4. 3次机会全部用完未触发 break，执行锁定提示
else:
    print('错误次数过多，账号已锁定！')





