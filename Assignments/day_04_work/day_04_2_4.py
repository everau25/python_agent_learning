# 假设你是一名便利店收银员，请使用 Python 编写一个收银系统，要求如下：
#
# 1. 系统可以**连续接待多位顾客**，直到收银员选择下班退出。
# 2. 每次结账时，需要键盘录入**商品单价**和**购买数量**，计算基础总价。
# 3. 询问顾客**是否为会员**（输入 `y` 或 `n`）。如果是会员，总价打 **8折**；非会员则原价支付。
# 4. 使用格式化输出（保留两位小数）打印顾客最终需要支付的金额。
# 5. 结账完成后，询问是否继续下一位顾客（输入 `y` 继续，输入其他字符退出系统）。
# 示例运行效果
# --- 欢迎使用智能便利店收银系统 ---
# 请输入商品单价: 15.5
# 请输入购买数量: 3
# 是否为会员(y/n): y
# => 会员您好，本次消费总计: 37.20 元
#
# 是否继续下一位顾客(y/n): y
# 请输入商品单价: 8
# 请输入购买数量: 2
# 是否为会员(y/n): n
# => 顾客您好，本次消费总计: 16.00 元
#
# 是否继续下一位顾客(y/n): n
# --- 感谢使用，系统已退出 ---
print("--- 欢迎使用智能便利店收银系统 ---")
while True:
    price = float(input('请输入商品单价'))
    num = int(input('请输入购买数量'))
    vip = input('是否为会员（y/n）:').strip().lower()
    total_price = price * num
    if vip == "y":
        total_price *= 0.8
        print(f"会员您好，本次消费总计:{total_price:.2f} 元")
    else:
        print(f"顾客您好，本次消费总计:{total_price:.2f} 元")
    service = input('是否继续下一位顾客(y/n):').strip().lower()
    if service != "y":
        print('--- 感谢使用，系统已退出 ---')
        break

